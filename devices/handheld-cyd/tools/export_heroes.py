#!/usr/bin/env python3
"""Export the companions' idle animation from the firmware for the station's Me panel picker.

Compiles a tiny host program against src/heroes.h (with a stand-in display that records pixels),
renders each hero's idle frames, and writes athena/src/pages/Settings/handheldHeroes.ts. The picker
then shows exactly what the handheld draws. Needs a C++ compiler (`c++`). Run after changing a hero:

    python3 devices/handheld-cyd/tools/export_heroes.py
"""
import json
import shutil
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "src"
OUT = HERE.parents[2] / "athena" / "src" / "pages" / "Settings" / "handheldHeroes.ts"

# Frames of the idle loop to export: breathing, blinking, sway, lantern flicker, then the fidget.
FRAMES = list(range(0, 16)) + list(range(40, 48))
RADIO = 0x00FF01  # stand-in for the radio light, recoloured by the page
CLEAR = 0xFF00FF

STUB = """#pragma once
#include <cstdint>
#include <cstring>
namespace lgfx {
struct LovyanGFX {
  int W, H; uint32_t* px;
  LovyanGFX(int w, int h) : W(w), H(h) { px = new uint32_t[w * h]; for (int i = 0; i < w * h; i++) px[i] = %d; }
  void fillRect(int x, int y, int w, int h, uint32_t c) {
    for (int j = y; j < y + h; j++) for (int i = x; i < x + w; i++) if (i >= 0 && j >= 0 && i < W && j < H) px[j * W + i] = c;
  }
  void drawPixel(int x, int y, uint32_t c) { fillRect(x, y, 1, 1, c); }
  void drawFastHLine(int x, int y, int w, uint32_t c) { fillRect(x, y, w, 1, c); }
};
}
""" % CLEAR

MAIN = """#include "heroes.h"
#include <cstdio>
using namespace art;
int main() {
  int frames[] = {%s};
  printf("%%d %%d\\n", (int)CH_COUNT, (int)(sizeof(frames) / sizeof(frames[0])));
  for (int c = 0; c < CH_COUNT; c++) {
    printf("%%s %%s\\n", characterId((Character)c), characterName((Character)c));
    for (int f : frames) {
      lgfx::LovyanGFX g(HERO_W, HERO_H);
      companion(g, 0, 0, 1, IDLE, f, %d, (Character)c);
      for (int i = 0; i < HERO_W * HERO_H; i++) printf("%%06x", g.px[i]);
      printf("\\n");
    }
  }
}
""" % (", ".join(map(str, FRAMES)), RADIO)

with tempfile.TemporaryDirectory() as tmp:
    t = Path(tmp)
    for name in ("art.h", "heroes.h"):
        shutil.copy(SRC / name, t / name)
    (t / "board.h").write_text(STUB)
    (t / "main.cpp").write_text(MAIN)
    subprocess.run(["c++", "-std=c++11", "-O1", "-o", str(t / "export"), str(t / "main.cpp")], check=True)
    lines = subprocess.run([str(t / "export")], check=True, capture_output=True, text=True).stdout.splitlines()

n_heroes, n_frames = map(int, lines[0].split())
KEYS = "0123456789bcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"

heroes = []
i = 1
for _ in range(n_heroes):
    hid, name = lines[i].split(" ", 1)
    i += 1
    colors: dict[int, str] = {CLEAR: ".", RADIO: "a"}
    unique: list[list[str]] = []
    sequence: list[int] = []
    for _ in range(n_frames):
        hexes = lines[i]
        i += 1
        px = [int(hexes[k : k + 6], 16) for k in range(0, len(hexes), 6)]
        for p in px:
            if p not in colors:
                colors[p] = KEYS[len(colors) - 2]
        rows = ["".join(colors[p] for p in px[r * 32 : r * 32 + 32]) for r in range(32)]
        if rows not in unique:
            unique.append(rows)
        sequence.append(unique.index(rows))
    palette = {v: f"#{k:06X}" for k, v in colors.items() if v not in (".", "a")}
    heroes.append({"id": hid, "name": name, "palette": palette, "frames": unique, "sequence": sequence})

ts = f"""// Generated by devices/handheld-cyd/tools/export_heroes.py from devices/handheld-cyd/src/heroes.h.
// Do not edit by hand: change the firmware art and run the script again.
//
// Each hero's idle animation as the handheld draws it, one 32×32 frame per tick (220 ms). `frames`
// holds the distinct frames and `sequence` the order to play them in. '.' is clear and 'a' is the
// radio light, which the page colours.

export type HeroFrames = {{
  id: string;
  name: string;
  palette: Record<string, string>;
  frames: string[][];
  sequence: number[];
}};

export const HERO_SIZE = 32;
export const FRAME_MS = 220;
/** The head box used for small portraits: 16×16 from (8, 0). */
export const PORTRAIT = {{ x: 8, y: 0, size: 16 }};
export const HEROES: HeroFrames[] = {json.dumps(heroes)};
"""
OUT.write_text(ts)
total = sum(len(h["frames"]) for h in heroes)
print(f"wrote {OUT.relative_to(HERE.parents[2])}: {len(heroes)} heroes, {total} distinct frames")
