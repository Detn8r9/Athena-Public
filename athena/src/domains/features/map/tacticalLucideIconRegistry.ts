const POI_LUCIDE_BY_NAME: Record<string, LucideIcon> = (() => {
  const m: Record<string, LucideIcon> = {};
  for (const row of POI_PRESET_ENTRIES) {
    m[row.lucideIconName] = row.Icon;
  }
  for (const row of POI_CUSTOM_LUCIDE_GRID) {
    m[row.name] = row.Icon;
  }
  return m;
})();

export function getPoiLucideIcon(lucideIconName: string): LucideIcon | undefined {
  return POI_LUCIDE_BY_NAME[lucideIconName];
}
